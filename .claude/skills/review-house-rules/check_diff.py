"""Check a change against this repo's house rules that no test enforces, and list the checks it calls for.

Usage (from the repo root):
    python .claude/skills/review-house-rules/check_diff.py                  # working tree + untracked files vs HEAD
    python .claude/skills/review-house-rules/check_diff.py --staged         # only what is staged
    python .claude/skills/review-house-rules/check_diff.py --base main      # everything that differs from main (commits + working tree)
    python .claude/skills/review-house-rules/check_diff.py --base main CharacterContent/   # limit to paths

Only *added* lines are checked, so old code that breaks a rule doesn't drown out the new change
(CLAUDE.md: old code is not precedent). What the test suite already enforces (layering, no
TYPE_CHECKING, the agent index, frontmatter) isn't repeated here; run the tests for those.

Prints one finding per line as `path:line  [check]  message`, then the verification commands
the changed files call for. Exit status 1 when there is any finding. A finding is a prompt to
look, not a verdict: the reviewer decides, and says why when it lets one stand.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]

# Sourcebook or edition text: origin= is the category a player reads, never where it was printed.
SOURCEBOOK = re.compile(
    r"\b(PHB|DMG|MM|XGE|XGtE|TCE|TCoE|SCAG|MotM|FToD|Player'?s Handbook|Dungeon Master'?s Guide|"
    r"Xanathar|Tasha|Fizban|Mordenkainen|Sword Coast|Unearthed Arcana|UA|2014|2024|5e|5\.5e|[Ee]dition)\b"
)
ORIGIN = re.compile(r"""origin\s*=\s*(f?["'])(.*?)\1""")
RULES_CONSTANTS = [
    (re.compile(r"range\(\s*1\s*,\s*21\s*\)"), "use Core.Rules.ALL_LEVELS, not range(1, 21)"),
    (re.compile(r"-\s*10\s*\)\s*//\s*2"), "use Core.Rules.ability_modifier(), not (score - 10) // 2"),
]
DEBUG = re.compile(r"^\s*(print\(|breakpoint\(\)|import pdb|pdb\.set_trace)")
ENGINE_DIRS = ("Model/", "Core/", "CharacterContent/")
SPELL_SOURCE_JSON = re.compile(r"^CharacterContent/Spells/spells_(dnd2024|dnd5e|aidedd)\.json$")
GENERATED_MONSTERS = re.compile(r"^Combat/Monsters/CR_[^/]+/(monsters|__init__)\.py$")
SCRATCH_NAME = re.compile(r"(^|/)(scratch|probe|tmp|temp|debug|try|test_out)[^/]*\.(py|txt|json)$", re.I)


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True).stdout


def added_lines(diff_args: list[str], paths: list[str]) -> dict[str, list[tuple[int, str]]]:
    """{path: [(line number, added text)]} from a zero-context diff."""
    out: dict[str, list[tuple[int, str]]] = {}
    path, line_no = None, 0
    for line in git("diff", "-U0", "--no-color", "--no-ext-diff", *diff_args, "--", *paths).splitlines():
        if line.startswith("+++ "):
            path = None if line == "+++ /dev/null" else line[6:]
            if path is not None:
                out.setdefault(path, [])
        elif line.startswith("@@"):
            match = re.search(r"\+(\d+)", line)
            line_no = int(match.group(1)) if match else 0
        elif line.startswith("+") and path is not None:
            out[path].append((line_no, line[1:]))
            line_no += 1
    return out


def changed_paths(diff_args: list[str], paths: list[str]) -> list[str]:
    return [p for p in git("diff", "--name-only", "--no-color", *diff_args, "--", *paths).splitlines() if p]


def untracked(paths: list[str]) -> list[str]:
    return [p for p in git("ls-files", "--others", "--exclude-standard", "--", *paths).splitlines() if p]


def is_generated_monster_file(path: str) -> bool:
    file = ROOT / path
    if not GENERATED_MONSTERS.match(path) or not file.exists():
        return False
    head = file.read_text(encoding="utf-8", errors="replace")[:3000]
    return "Auto-generated by generate_monsters.py" in head and "hand-edited" not in head


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", nargs="*", help="limit to these files or folders")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--staged", action="store_true", help="check only the staged changes")
    group.add_argument("--base", metavar="REF", help="check everything that differs from REF (default HEAD)")
    args = parser.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    diff_args = ["--cached"] if args.staged else [args.base or "HEAD"]
    paths = args.paths
    added = added_lines(diff_args, paths)
    changed = changed_paths(diff_args, paths)
    new_files = [] if args.staged else untracked(paths)
    for path in new_files:
        file = ROOT / path
        if file.suffix in (".py", ".json", ".md", ".txt") and file.stat().st_size < 2_000_000:
            text = file.read_text(encoding="utf-8", errors="replace")
            added[path] = list(enumerate(text.splitlines(), start=1))
    changed = sorted({*changed, *new_files})
    changed = [p for p in changed if not p.startswith((".claude/worktrees/", ".git/"))]

    findings: list[str] = []

    def find(path: str, line: int | None, check: str, message: str) -> None:
        findings.append(f"{path}{f':{line}' if line else ''}  [{check}]  {message}")

    for path in changed:
        if is_generated_monster_file(path):
            find(path, None, "generated-file", "generate_monsters.py overwrites this file; put homebrew monsters in monsters_homebrew.py")
        if SPELL_SOURCE_JSON.match(path):
            find(path, None, "spell-source", "scraper output: only a scraper run should change it. usage_tags go in spells_<source>_extended.json, descriptions in _improved.json")
        if path in new_files and path.endswith(".py") and ("/" not in path or SCRATCH_NAME.search(path)) and not path.startswith(("tests/", "Run")):
            find(path, None, "scratch-file", "new file looks like a scratch script; scratch scripts belong in the scratchpad, not the repo")
        if path in new_files and path.startswith("CharacterContent/Classes/SubClasses2014/"):
            twin = ROOT / path.replace("SubClasses2014", "SubClasses2024")
            if twin.exists():
                find(path, None, "2014-reprint", f"a 2024 version exists ({twin.relative_to(ROOT).as_posix()}); 2014 subclasses with a 2024 reprint are not added")

    for path, lines in added.items():
        if not path.endswith(".py") or path.startswith((".claude/", "tests/")):
            continue
        for line_no, text in lines:
            for match in ORIGIN.finditer(text):
                hit = SOURCEBOOK.search(match.group(2))
                if hit:
                    find(path, line_no, "origin", f"origin={match.group(2)!r} names a source ({hit.group(0)!r}); origin is the category a player reads, e.g. 'Bard Level 9'")
            if path != "Core/Rules.py":
                for pattern, message in RULES_CONSTANTS:
                    if pattern.search(text):
                        find(path, line_no, "rules-constant", message)
            if path.startswith(ENGINE_DIRS) and DEBUG.match(text):
                find(path, line_no, "debug", "debug output left in engine/content code")

    print(f"Checked {len(changed)} changed file(s) against {'the index' if args.staged else args.base or 'HEAD'}.")
    if findings:
        print("\nFindings:")
        print("\n".join(f"  {f}" for f in findings))
    else:
        print("\nFindings: none.")

    # What the change calls for, by which files it touched.
    todo = []
    text_of = lambda p: "\n".join(t for _, t in added.get(p, []))
    if any(p.endswith(".py") for p in changed):
        todo.append("./run_tests.sh -q   (compile, layering, contracts, order invariance, snapshots)")
    if any(p.startswith(("Model/", "Core/", "CharacterContent/", "Builds/", "Presentation/")) for p in changed) or any(p.startswith("tests/snapshots/") for p in changed):
        todo.append("python .claude/skills/snapshot-diffs/snapshot_diff.py   (read every sheet change; a snapshot is never 'expected' unread)")
    if any("usage_tags" in text_of(p) for p in changed if not p.startswith(".claude/")) or any(p.endswith("_extended.json") for p in changed):
        todo.append("python .claude/skills/usage-tags/tag_report.py check")
    if any(p.endswith("monsters_homebrew.py") for p in changed):
        todo.append('python .claude/skills/balance-monster/check_monster.py "<each changed monster>"   (score 0.4-0.6, at most 4 abilities)')
    if any(p.startswith((".claude/agents/", ".claude/skills/", ".claude/hooks/")) or p == "CLAUDE.md" for p in changed):
        todo.append("./run_tests.sh -q tests/test_claude_config.py tests/test_skill_scripts.py")
    if any(p.startswith(".claude/agent-memory/") for p in changed):
        todo.append("git diff -- .claude/agent-memory/   (curate: delete wrong lessons, promote proven ones)")
    if any(p.startswith(("Builds/CharacterCreator/", "Combat/CombatUIQt/")) for p in changed):
        todo.append("python .claude/skills/run-apps/screenshot.py ...   (look at the changed window, not just the tests)")
    if todo:
        print("\nThis change also calls for:")
        print("\n".join(f"  {t}" for t in todo))
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())

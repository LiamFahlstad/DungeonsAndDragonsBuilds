"""Scrape the D&D 2024 Rules Glossary from D&D Beyond into a local folder tree of Markdown files.

Usage (from the repo root):
    python .claude/skills/rules-glossary/scrape_rules_glossary.py                 # fetch and (re)write SourceTexts/RulesGlossary/
    python .claude/skills/rules-glossary/scrape_rules_glossary.py --html page.html  # render a saved copy of the page instead
    python .claude/skills/rules-glossary/scrape_rules_glossary.py --out some/dir    # write somewhere else

The page is one long article: every glossary entry is an <h3>, its sub-sections are <h4>s. Each
entry becomes <folder>/<Name>.md, where the folder comes from categories.json next to this file:
an entry with a tag in brackets ("Attack [Action]") goes to the folder of its tag, any other
entry to the folder that lists it by name. Every folder gets an index.md, and the top index.md
holds the glossary conventions and an A-Z list. Links between entries become relative links.

Every file the script writes starts with GENERATED_MARKER; a re-run deletes the generated files
it didn't rewrite (an entry that was removed or moved), and never touches any other file.

Exit status: 0 when every entry has a folder; 1 when some went to Uncategorized/ (add them to
categories.json and run again).
"""

import argparse
import datetime
import json
import os
import re
import sys
import time
from pathlib import Path

import requests
from bs4 import BeautifulSoup, NavigableString, Tag

SKILL_DIR = Path(__file__).resolve().parent
REPO_ROOT = SKILL_DIR.parent.parent.parent
CATEGORIES = SKILL_DIR / "categories.json"
DEFAULT_OUT = REPO_ROOT / "SourceTexts" / "RulesGlossary"

SITE = "https://www.dndbeyond.com"
GLOSSARY_URL = SITE + "/sources/dnd/br-2024/rules-glossary"
# Other pages link to the same glossary under these paths; their anchors resolve locally too.
GLOSSARY_PATHS = (
    "/sources/dnd/br-2024/rules-glossary",
    "/sources/dnd/free-rules/rules-glossary",
)
HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/124.0 Safari/537.36"
}

UNCATEGORIZED = "Uncategorized"
INDEX = "index.md"
GENERATED_MARKER = "<!-- Generated by .claude/skills/rules-glossary/scrape_rules_glossary.py - do not edit. -->"

TAG_RE = re.compile(r"^(?P<name>.*?)\s*\[(?P<tag>[^\]]+)\]$")
QUOTES = str.maketrans({"‘": "'", "’": "'", "“": '"', "”": '"', "\xa0": " "})


# ---------------------------------------------------------------- fetching


def fetch_html(retries: int = 3) -> str:
    for attempt in range(retries):
        try:
            response = requests.get(GLOSSARY_URL, headers=HEADERS, timeout=30)
            response.raise_for_status()
            response.encoding = "utf-8"
            return response.text
        except requests.RequestException as error:
            if attempt == retries - 1:
                raise
            print(f"  retrying {GLOSSARY_URL} ({error})", file=sys.stderr)
            time.sleep(2)
    raise AssertionError("unreachable")


# ---------------------------------------------------------------- parsing


class Entry:
    def __init__(self, heading: Tag):
        self.heading = heading
        self.title = clean(heading.get_text(" ", strip=True))
        match = TAG_RE.match(self.title)
        self.name = match["name"] if match else self.title
        self.tag = match["tag"] if match else None
        self.anchor = heading.get("id", "")
        self.blocks = blocks_until_next(heading, ("h2", "h3"))
        self.folder = ""

    @property
    def path(self) -> str:
        """Path relative to the output root, with forward slashes."""
        return f"{self.folder}/{file_stem(self.name)}.md"


def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.translate(QUOTES))


def file_stem(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-")


def heading_slug(text: str) -> str:
    """The fragment GitHub and VS Code give a Markdown heading."""
    return re.sub(r"[^\w\- ]", "", text.lower()).strip().replace(" ", "-")


def blocks_until_next(heading: Tag, stop_tags: tuple[str, ...]) -> list[Tag]:
    blocks = []
    for sibling in heading.find_next_siblings():
        if sibling.name in stop_tags:
            break
        blocks.append(sibling)
    return blocks


def parse(html: str) -> tuple[list[Tag], list[Entry]]:
    soup = BeautifulSoup(html, "html.parser")
    content = soup.select_one(".p-article-content")
    if content is None:
        sys.exit(
            "The page has no .p-article-content block; D&D Beyond changed its layout."
        )
    conventions = content.find("h2", id="GlossaryConventions")
    convention_blocks = blocks_until_next(conventions, ("h2",)) if conventions else []
    entries = [Entry(h3) for h3 in content.find_all("h3")]
    if not entries:
        sys.exit("Found no <h3> entries on the page; D&D Beyond changed its layout.")
    return convention_blocks, entries


def assign_folders(entries: list[Entry], categories: dict) -> list[Entry]:
    """Set each entry's folder; return the entries that matched no rule."""
    by_name = {
        name: folder
        for folder, spec in categories["folders"].items()
        for name in spec["entries"]
    }
    tag_folders = categories["tags"]
    unmatched = []
    for entry in entries:
        if entry.tag in tag_folders:
            entry.folder = tag_folders[entry.tag]
        elif entry.name in by_name:
            entry.folder = by_name[entry.name]
        elif entry.name in tag_folders:  # "Action" lives with the [Action] entries
            entry.folder = tag_folders[entry.name]
        else:
            entry.folder = UNCATEGORIZED
            unmatched.append(entry)
    return unmatched


# ---------------------------------------------------------------- rendering


class Renderer:
    """Turns the page's HTML blocks into Markdown, resolving glossary anchors to local files."""

    def __init__(self, entries: list[Entry]):
        # anchor id -> (path relative to the output root, fragment or "")
        self.anchors: dict[str, tuple[str, str]] = {}
        for entry in entries:
            self.anchors[entry.anchor] = (entry.path, "")
            for sub in (
                b
                for block in entry.blocks
                for b in [block, *block.find_all("h4")]
                if b.name == "h4"
            ):
                self.anchors[sub.get("id", "")] = (
                    entry.path,
                    heading_slug(clean(sub.get_text(" ", strip=True))),
                )
        self.current = ""  # path of the file being rendered, for relative links

    def link(self, href: str) -> str:
        path, _, fragment = href.partition("#")
        # The page itself has a few singular/plural slips ("#OpportunityAttack" for "#OpportunityAttacks").
        fragment = next(
            (
                f
                for f in (fragment, fragment + "s", fragment.removesuffix("s"))
                if f in self.anchors
            ),
            fragment,
        )
        if path in ("", *GLOSSARY_PATHS) and fragment in self.anchors:
            target, sub = self.anchors[fragment]
            relative = os.path.relpath(
                target, os.path.dirname(self.current) or "."
            ).replace(os.sep, "/")
            return relative + (f"#{sub}" if sub else "")
        if path == "":
            return f"{GLOSSARY_URL}#{fragment}"
        return href if href.startswith("http") else SITE + href

    def inline(self, node) -> str:
        if isinstance(node, NavigableString):
            return clean(str(node))
        if not isinstance(node, Tag) or node.name in ("img", "figure"):
            return ""
        text = "".join(self.inline(child) for child in node.children)
        if node.name == "br":
            return "  \n"
        if node.name in ("strong", "b"):
            return wrap(text, "**")
        if node.name in ("em", "i"):
            return wrap(text, "*")
        if node.name == "a" and node.get("href") and text.strip():
            return wrap(text, "[", f"]({self.link(node['href'])})")
        return text

    def blocks(self, blocks: list[Tag], heading_level: int = 2) -> str:
        parts = []
        for block in blocks:
            if block.name == "p":
                parts.append(self.inline(block).strip())
            elif block.name in ("h3", "h4"):
                parts.append("#" * heading_level + " " + self.inline(block).strip())
            elif block.name == "ul":
                parts.append(
                    "\n".join(
                        f"- {self.inline(li).strip()}" for li in block.find_all("li")
                    )
                )
            elif block.name == "div" and any(
                "column" in c for c in block.get("class", [])
            ):
                parts.append(
                    "\n".join(
                        f"- {self.inline(p).strip()}" for p in block.find_all("p")
                    )
                )
            elif block.name == "table":
                parts.append(self.table(block, heading_level))
            # hr separators, figures (art) and the page-navigation div carry no rules text.
        return "\n\n".join(part for part in parts if part)

    def table(self, table: Tag, heading_level: int) -> str:
        lines = []
        caption = table.find("caption")
        if caption:
            title = self.inline(caption).strip()
            lines += [
                (
                    "#" * heading_level + " " + title
                    if caption.find("h4")
                    else f"**{title}**"
                ),
                "",
            ]
        rows = [
            [
                self.inline(cell).strip().replace("|", "\\|")
                for cell in tr.find_all(["th", "td"])
            ]
            for tr in table.find_all("tr")
        ]
        rows = [row for row in rows if row]
        if not rows:
            return ""
        width = max(len(row) for row in rows)
        first = table.find("tr")
        if any(cell.name == "td" for cell in first.find_all(["th", "td"])):
            # No header row (the abbreviations table only has row headers): Markdown needs one,
            # so add an empty one rather than promote a data row.
            rows.insert(0, [""] * width)
        rows = [row + [""] * (width - len(row)) for row in rows]
        lines.append("| " + " | ".join(rows[0]) + " |")
        lines.append("|" + "---|" * width)
        lines += ["| " + " | ".join(row) + " |" for row in rows[1:]]
        return "\n".join(lines)


def wrap(text: str, before: str, after: str | None = None) -> str:
    """Wrap text in Markdown markers, keeping its outer whitespace outside them."""
    stripped = text.strip()
    if not stripped:
        return text
    leading = text[: len(text) - len(text.lstrip())]
    trailing = text[len(text.rstrip()) :]
    return f"{leading}{before}{stripped}{before if after is None else after}{trailing}"


def summary(entry: Entry) -> str:
    first = next((b for b in entry.blocks if b.name == "p"), None)
    if first is None:
        return ""
    text = clean(first.get_text(" ", strip=True))
    text = re.sub(r"\s+([.,;:])", r"\1", text)
    sentence = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return sentence if len(sentence) <= 200 else sentence[:197].rstrip() + "..."


def breadcrumb(folder: str) -> str:
    return " > ".join(part.replace("-", " ") for part in folder.split("/"))


# ---------------------------------------------------------------- pages


def entry_page(entry: Entry, renderer: Renderer) -> str:
    renderer.current = entry.path
    up = os.path.relpath(INDEX, entry.folder).replace(os.sep, "/")
    source = f"[D&D Beyond]({GLOSSARY_URL}#{entry.anchor})"
    lines = [
        GENERATED_MARKER,
        "",
        f"# {entry.title}",
        "",
        f"*[Rules Glossary]({up}) > [{breadcrumb(entry.folder)}]({INDEX}) | {source}*",
        "",
        renderer.blocks(entry.blocks),
    ]
    return "\n".join(lines).rstrip() + "\n"


def folder_page(
    folder: str, description: str, entries: list[Entry], subfolders: list[str]
) -> str:
    up = os.path.relpath(INDEX, folder).replace(os.sep, "/")
    lines = [
        GENERATED_MARKER,
        "",
        f"# {breadcrumb(folder)}",
        "",
        f"*[Rules Glossary]({up})*",
        "",
    ]
    if description:
        lines += [description, ""]
    if subfolders:
        lines += ["## Sections", ""]
        for sub in subfolders:
            lines.append(
                f"- [{sub.rsplit('/', 1)[-1].replace('-', ' ')}]({sub[len(folder) + 1:]}/{INDEX})"
            )
        lines.append("")
    if entries:
        lines += ["## Entries", ""]
        for entry in sorted(entries, key=lambda e: e.title.lower()):
            line = f"- [{entry.title}]({file_stem(entry.name)}.md)"
            lines.append(f"{line}: {summary(entry)}" if summary(entry) else line)
    return "\n".join(lines).rstrip() + "\n"


def root_page(
    conventions: list[Tag],
    entries: list[Entry],
    folders: dict[str, str],
    renderer: Renderer,
) -> str:
    renderer.current = INDEX
    counts = {
        folder: sum(
            1
            for e in entries
            if e.folder == folder or e.folder.startswith(folder + "/")
        )
        for folder in folders
    }
    lines = [
        GENERATED_MARKER,
        "",
        "# Rules Glossary (D&D 2024)",
        "",
        f"Scraped from [{GLOSSARY_URL}]({GLOSSARY_URL}) on {datetime.date.today().isoformat()}: "
        f"{len(entries)} entries, one file each, grouped by topic.",
        "",
        "## Sections",
        "",
        "| Section | Entries | What's in it |",
        "|---|---|---|",
    ]
    for folder, description in folders.items():
        if counts[folder]:
            name = ("&nbsp;&nbsp;&nbsp;&nbsp;" * folder.count("/")) + folder.rsplit(
                "/", 1
            )[-1].replace("-", " ")
            lines.append(
                f"| [{name}]({folder}/{INDEX}) | {counts[folder]} | {description} |"
            )
    if conventions:
        lines += [
            "",
            "## Glossary Conventions",
            "",
            renderer.blocks(conventions, heading_level=3),
        ]
    lines += ["", "## All Entries", ""]
    for letter in sorted({e.title[0].upper() for e in entries}):
        lines += [f"### {letter}", ""]
        for entry in sorted(
            (e for e in entries if e.title[0].upper() == letter),
            key=lambda e: e.title.lower(),
        ):
            lines.append(
                f"- [{entry.title}]({entry.path}) ({breadcrumb(entry.folder)})"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------- writing


def generated_files(out: Path) -> set[Path]:
    if not out.is_dir():
        return set()
    found = set()
    for path in out.rglob("*.md"):
        with path.open(encoding="utf-8") as file:
            if file.readline().rstrip("\n") == GENERATED_MARKER:
                found.add(path)
    return found


def write_all(out: Path, pages: dict[str, str]) -> tuple[list[Path], list[Path], int]:
    """Write pages ({relative path: text}); return (created, deleted, changed count)."""
    before = generated_files(out)
    created, changed = [], 0
    for relative, text in pages.items():
        path = out / relative
        if path.exists() and path not in before:
            sys.exit(
                f"Refusing to overwrite {path}: it was not generated by this script."
            )
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old is None:
            created.append(path)
        if old != text:
            changed += 1
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    written = {out / relative for relative in pages}
    deleted = sorted(before - written)
    for path in deleted:
        path.unlink()
    for directory in sorted(
        {p.parent for p in deleted}, key=lambda d: len(d.parts), reverse=True
    ):
        while directory != out and directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
            directory = directory.parent
    return created, deleted, changed


def build_pages(
    conventions: list[Tag], entries: list[Entry], categories: dict
) -> dict[str, str]:
    folders = {
        folder: spec["description"] for folder, spec in categories["folders"].items()
    }
    if any(e.folder == UNCATEGORIZED for e in entries):
        folders[UNCATEGORIZED] = "Entries categories.json doesn't place yet."
    seen: dict[str, Entry] = {}
    for entry in entries:
        if entry.path in seen:
            sys.exit(
                f"'{entry.title}' and '{seen[entry.path].title}' would both be written to {entry.path}."
            )
        seen[entry.path] = entry

    renderer = Renderer(entries)
    pages = {entry.path: entry_page(entry, renderer) for entry in entries}
    for folder, description in folders.items():
        in_folder = [e for e in entries if e.folder == folder]
        subfolders = [
            f
            for f in folders
            if f.startswith(folder + "/") and "/" not in f[len(folder) + 1 :]
        ]
        if in_folder or subfolders:
            pages[f"{folder}/{INDEX}"] = folder_page(
                folder, description, in_folder, subfolders
            )
    pages[INDEX] = root_page(conventions, entries, folders, renderer)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--html",
        type=Path,
        help="render a saved copy of the glossary page instead of fetching it",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help=f"output folder (default {DEFAULT_OUT})",
    )
    args = parser.parse_args()

    html = args.html.read_text(encoding="utf-8") if args.html else fetch_html()
    categories = json.loads(CATEGORIES.read_text(encoding="utf-8"))
    conventions, entries = parse(html)
    unmatched = assign_folders(entries, categories)

    known = {
        name for spec in categories["folders"].values() for name in spec["entries"]
    }
    stale = sorted(known - {e.name for e in entries if not e.tag})

    pages = build_pages(conventions, entries, categories)
    out = args.out.resolve()
    created, deleted, changed = write_all(out, pages)

    print(f"{len(entries)} entries -> {out}")
    for folder in categories["folders"]:
        count = sum(1 for e in entries if e.folder == folder)
        if count:
            print(f"  {folder:<28} {count:>3}")
    print(
        f"{len(pages)} files: {len(created)} new, {changed - len(created)} changed, {len(deleted)} deleted"
    )
    for path in created:
        print(f"  new      {path.relative_to(out).as_posix()}")
    for path in deleted:
        print(f"  deleted  {path.relative_to(out).as_posix()}")
    if stale:
        print(f"categories.json lists names the page no longer has: {', '.join(stale)}")
    if unmatched:
        print(f"UNCATEGORIZED ({len(unmatched)}), add them to categories.json:")
        for entry in unmatched:
            print(f"  {entry.title}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Generate .claude/skills/agent-index/SKILL.md: the index of every project agent and skill.

Usage (from the repo root):
    python .claude/skills/agent-index/build_index.py           # rewrite the index
    python .claude/skills/agent-index/build_index.py --check   # exit 1 if the index is stale (the test suite runs this)

Everything in the index comes from the agents' and skills' own frontmatter, so it can't drift from
them: change an agent or skill, rerun this (a PostToolUse hook does it automatically after Edit/Write
on those files), and the index follows. Don't edit SKILL.md by hand; edit the generator's text below.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
AGENTS = ROOT / ".claude" / "agents"
SKILLS = ROOT / ".claude" / "skills"
OUT = SKILLS / "agent-index" / "SKILL.md"
SUMMARY_CHARS = 130

FRONTMATTER = """---
name: agent-index
description: Generated index of every project agent and skill - what each is for, its model, the skills it preloads, which agents point to each other, and each skill's scripts. Use when choosing which agent or skill fits a task (especially between similar ones, e.g. dnd-builds vs dnd-subclass-creator vs dnd-equipment), when the user asks what agents or skills exist or what one does, and before adding or changing an agent or skill, to avoid overlap.
---
"""

INTRO = """# Agent and skill index

<!-- Generated by .claude/skills/agent-index/build_index.py from frontmatter. Don't edit by hand. -->

Every row comes from the agent's or skill's own frontmatter, so this can't drift from them. The **use for** column is the opening of each description. The full description, which Claude Code routes on, is in the linked file. How to brief, pick a model and verify is in CLAUDE.md, and the reasoning behind the setup is in `Notes/agent-workflow.md`.

**Picking:** use the specialist whose *use for* matches, and check its **points to** column for the "not for this, use that" neighbours. Fall back to `dnd-builds` or `combat-sim` for general work. Do small edits in the main session without an agent. A skill marked *main session* is used directly rather than preloaded.
"""


def frontmatter(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8").split("---\n", 2)[1]) or {}


def summary(description: str) -> str:
    """The description's opening clause, without leading 'Use to/for/when' or parenthetical asides."""
    text = re.split(r" — |(?<!e\.g)(?<!i\.e)\. ", description, maxsplit=1)[0].rstrip(".")
    text = re.sub(r" \([^()]*\)", "", text)
    text = re.sub(r"^Use (for|to|when) ", "", text)
    text = text[0].upper() + text[1:]
    if len(text) > SUMMARY_CHARS:
        text = text[:SUMMARY_CHARS].rsplit(" ", 1)[0] + "…"
    return text.replace("|", "\\|")


def link(path: Path) -> str:
    # Relative to the index file, so links work in an editor and on GitHub.
    return Path("../..", path.relative_to(ROOT / ".claude")).as_posix()


def build() -> str:
    agents = []
    for path in sorted(AGENTS.rglob("*.md")):
        meta = frontmatter(path)
        if meta.get("name"):
            agents.append((path, meta))
    names = [meta["name"] for _, meta in agents]

    skills = []
    for path in sorted(SKILLS.glob("*/SKILL.md")):
        if path == OUT:
            continue
        skills.append((path, frontmatter(path)))

    lines = [FRONTMATTER, INTRO]
    lines.append(f"## Agents ({len(agents)})\n")
    by_domain: dict[str, list] = {}
    for path, meta in agents:
        domain = path.parent.relative_to(AGENTS).as_posix() if path.parent != AGENTS else "(top level)"
        by_domain.setdefault(domain, []).append((path, meta))
    for domain, members in by_domain.items():
        lines.append(f"### {domain}/\n")
        lines.append("| Agent | Model | Preloads | Use for | Points to |")
        lines.append("|---|---|---|---|---|")
        for path, meta in members:
            mentions = [n for n in names if n != meta["name"] and re.search(rf"\b{re.escape(n)}\b", meta["description"])]
            preloads = ", ".join(f"`{s}`" for s in meta.get("skills") or []) or "-"
            points = ", ".join(f"`{n}`" for n in mentions) or "-"
            lines.append(
                f"| [`{meta['name']}`]({link(path)}) | {meta.get('model', 'inherit')} | {preloads} "
                f"| {summary(meta['description'])} | {points} |"
            )
        lines.append("")

    lines.append(f"## Skills ({len(skills)})\n")
    lines.append("| Skill | Preloaded by | Scripts | Use for |")
    lines.append("|---|---|---|---|")
    for path, meta in skills:
        users = [m["name"] for _, m in agents if meta["name"] in (m.get("skills") or [])]
        scripts = ", ".join(f"`{p.name}`" for p in sorted(path.parent.glob("*.py"))) or "-"
        used = ", ".join(f"`{u}`" for u in users) or "*main session*"
        lines.append(f"| [`{meta['name']}`]({link(path)}) | {used} | {scripts} | {summary(meta['description'])} |")
    lines.append("")
    lines.append("This skill itself (`agent-index`) is the index, generated by `build_index.py` in this folder.")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the index is out of date, without writing")
    args = parser.parse_args()
    text = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print(f"{OUT.relative_to(ROOT).as_posix()} is stale: run python .claude/skills/agent-index/build_index.py")
            return 1
        print("index is up to date")
        return 0
    if current != text:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
